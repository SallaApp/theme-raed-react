"""
Regenerates app/lib/glizer/variantData.ts from Glizer's Salla-export workbook (TD-17507).

    python3 -m venv .venv && .venv/bin/pip install openpyxl
    .venv/bin/python scripts/glizer-variant-data.py "<path to the .xlsx>"

Reads sheet «كل الاحتمالات» (col A = Salla product id, B = product group,
G-L = option names/values) and «مكررات (No. بديلة)» (duplicate ids).
"""
import sys, json, collections, openpyxl

wb = openpyxl.load_workbook(sys.argv[1], read_only=True, data_only=True)
rows = []
for r in list(wb['كل الاحتمالات'].iter_rows(values_only=True))[1:]:
    if not isinstance(r[0], int): continue
    rows.append(dict(id=r[0], pid=r[1], name=r[2], store=r[5],
        opts=[[k, str(v).strip()] for k, v in zip(r[6:9], r[9:12]) if k and v is not None]))
dups = [dict(main=r[0], alt=r[1]) for r in list(wb['مكررات (No. بديلة)'].iter_rows(values_only=True))[1:]
        if isinstance(r[0], int) and isinstance(r[1], int)]
# Listed «متاح» in the export but 404 on the storefront (checked 2026-11-03): a
# button to them would open «الصفحة غير موجودة». Remove an id once it opens again.
NOT_ON_STORE = {
    242577895, 1966921370,              # ببجي اكواد: 660 / 325 شدة
    1442174093,                         # ايتونز سعودي 500 ريال
    1222515677, 1954568671,             # بلايستيشن سعودي 40 / 60 دولار
    1727034362, 855876480,              # ببجي عن طريق الايدي: 3850 / 32400 شدة كاش
    1468061882, 1055720231,             # فري فاير 260 / 2800 جوهرة
    2062411601, 2116935511,             # يلا لودو: 168860 ماسة تقسيط / 25236460 ذهب كاش
    196067480, 20852123,                # تعبئة رصيد المحفظة 1500 / 2000 تقسيط
    1143339880,                         # duplicate of 67493602 (ببجي 1800 شدة)
}
rows = [r for r in rows if r['id'] not in NOT_ON_STORE]
dups = [x for x in dups if x['alt'] not in NOT_ON_STORE]
d = dict(rows=rows, dups=dups)
OUT = "app/lib/glizer/variantData.ts"
# Products split by store that the customer picks between on one page.
MERGE = {2: 'بطاقة ايتونز ابل ستور', 3: 'بطاقة ايتونز ابل ستور',
         10: 'بطاقة بلايستيشن ستور', 15: 'بطاقة بلايستيشن ستور'}
groups = collections.OrderedDict()
for r in d['rows']:
    if not r['opts']: continue
    name = MERGE.get(r['pid'], r['name'])
    opts = ([['المتجر', r['store']]] if r['pid'] in MERGE else []) + r['opts']
    g = groups.setdefault(name, {'keys': [k for k, _ in opts], 'members': []})
    assert g['keys'] == [k for k, _ in opts], (name, g['keys'], opts)
    g['members'].append([r['id']] + [v for _, v in opts])
groups = {n: g for n, g in groups.items() if len(g['members']) > 1}
ids = {m[0] for g in groups.values() for m in g['members']}
aliases = {x['alt']: x['main'] for x in d['dups'] if x['main'] in ids}
out = ["/* GENERATED by scripts/glizer-variant-data.py (TD-17507); do not edit by hand. Source: قلايزر_حصر_الخيارات_والاحتمالات_من_تصدير_سلة.xlsx, sheet «كل الاحتمالات». */",
       "import type { StaticVariantGroup } from '../staticVariants';", "",
       "export const GLIZER_VARIANT_GROUPS: StaticVariantGroup[] = ["]
for n, g in groups.items():
    out.append(f"  {{ name: {json.dumps(n, ensure_ascii=False)}, keys: {json.dumps(g['keys'], ensure_ascii=False)}, members: [")
    for m in g['members']:
        out.append('    ' + json.dumps(m, ensure_ascii=False) + ',')
    out.append('  ] },')
out += ['];', '', '/** Duplicate products → the product with the same values listed above. */',
        'export const GLIZER_VARIANT_ALIASES: Record<number, number> = {']
out += [f'  {a}: {m},' for a, m in aliases.items()]
out += ['};', '']
open(OUT, "w").write('\n'.join(out))
print(len(groups), 'groups', len(ids), 'products', len(aliases), 'aliases', 'dropped dups', len(d['dups']) - len(aliases))
